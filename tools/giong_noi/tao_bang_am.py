"""Build audio/tts/vi_phonemes.tsv: Vietnamese syllable -> the phonemes the Piper vi_VN voices were trained on.

Dev-time only. It runs the espeak-ng program (GPL-3.0, installed separately, never shipped) once per syllable
and stores its output as data, so Clicky itself carries no espeak-ng code. sherpa-onnx 2.0 removed espeak-ng
for the same reason; the voice then takes these phonemes directly.

Each syllable gets two forms because espeak marks the level tone differently at the end of a clause
("hai" mid-clause hˈaː1j, at the end hˈaː7j). Words come from Vietnamese text in the repo and the project
documents, plus the recognizer's vocabulary.

    python tools/giong_noi/tao_bang_am.py --words words.txt   # one word per line
"""
from __future__ import annotations

import argparse
import sys
import re
import unicodedata
import subprocess
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "audio" / "tts" / "vi_phonemes.tsv"
_FLAG = re.compile(r"\((?:en|vi)\)")


TONES = ("", "\u0300", "\u0301", "\u0309", "\u0303", "\u0323")       # ngang huyền sắc hỏi ngã nặng
VOWELS = "aăâeêioôơuưy"


def toneless(word: str) -> str:
    d = unicodedata.normalize("NFD", word)
    return unicodedata.normalize("NFC", "".join(c for c in d if c not in TONES[1:]))


def with_tone(base: str, mark: str) -> str:
    """Put a tone mark where Vietnamese spelling puts it (new style, e.g. 'hoá', 'thuý')."""
    if not mark:
        return base
    idx = [i for i, c in enumerate(base) if c in VOWELS]
    if base.startswith(("qu", "gi")) and len(idx) > 1:
        idx = idx[1:]
    if not idx:
        return base
    special = [i for i in idx if base[i] in "ăâêôơư"]
    if special:
        pos = special[-1]
    elif idx[-1] < len(base) - 1 or len(idx) == 1:
        pos = idx[-1]                          # closed syllable, or one vowel: the last vowel
    elif base[idx[-2]:idx[-1] + 1] in ("oa", "oe", "uy"):
        pos = idx[-1]
    else:
        pos = idx[-2] if len(idx) >= 2 else idx[-1]
    return unicodedata.normalize("NFC", base[:pos + 1] + mark + base[pos + 1:])


def all_tones(words: set) -> set:
    out = set(words)
    for w in words:
        if w.isalpha():
            base = toneless(w)
            out.update(with_tone(base, m) for m in TONES)
    return out


def espeak(text: str) -> list:
    out = subprocess.run(["espeak-ng", "-v", "vi", "-q", "--ipa", text], capture_output=True, text=True).stdout
    return _FLAG.sub("", out).split()


def phonemes(word: str):
    mid, end = espeak(f"ba {word} ba"), espeak(f"ba {word}")
    if len(mid) == 3 and len(end) == 2:
        return word, mid[1], end[1]
    return word, None, None


def main(argv=None) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser()
    ap.add_argument("--words", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args(argv)
    words = {unicodedata.normalize("NFC", w.strip().lower()) for w in a.words.read_text(encoding="utf-8").split() if w.strip()}
    vietnamese = {w for w in words if not w.isascii() or len(w) <= 4}
    words = sorted(words | all_tones(vietnamese))
    with ThreadPoolExecutor(8) as ex:
        rows = [r for r in ex.map(phonemes, words) if r[1]]
    a.out.write_text("# word\tmid-clause\tclause-final   (generated by tools/giong_noi/tao_bang_am.py)\n" +
                     "".join(f"{w}\t{m}\t{e}\n" for w, m, e in rows), encoding="utf-8")
    print(f"{len(rows)}/{len(words)} từ -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
